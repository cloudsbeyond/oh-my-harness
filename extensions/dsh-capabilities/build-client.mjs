/** Generate client.js by inlining the browser-safe preview core into the
 * lazy-factory template. One source of truth; the artifact is committed and
 * tests assert `build()` output equals the committed file. Run:
 *   node extensions/dsh-capabilities/build-client.mjs */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const here = path.dirname(fileURLToPath(import.meta.url));

export function build() {
  const core = readFileSync(path.join(here, 'audio-preview-core.mjs'), 'utf8')
    .replace(/^export const /gm, 'const ')
    .replace(/^export function /gm, 'function ')
    .replace(/^export async function /gm, 'async function ');

  return `/** GENERATED by build-client.mjs — do not edit inline logic.
 * Plugin-owned WAV preview for the Host document preview tab. */
window.__ModuleLoader__.load({
  id: 'oh-my-harness',
  factory(require) {
    const React = require('react');
    const h = React.createElement;
    const { useCallback, useEffect, useRef, useState } = React;

${core.split('\n').map((line) => (line ? `    ${line}` : '')).join('\n')}

    function AudioBody({ resourceAddress, content, workspaceFiles }) {
      const [state, setState] = useState(undefined);
      const audioRef = useRef(undefined);
      // React clears refs before passive-effect cleanup. Stop the old element
      // at detachment as well, so a removed audio node cannot keep playing.
      const setAudioRef = useCallback((element) => {
        const previous = audioRef.current;
        if (previous && previous !== element) { previous.pause(); previous.removeAttribute('src'); previous.load(); }
        audioRef.current = element;
      }, []);
      const revision = content.revision;
      useEffect(() => {
        const controller = new AbortController();
        const owner = { resourceAddress, revision, workspaceFiles };
        let objectUrl;
        let disposed = false;
        setState(undefined);
        const release = () => {
          if (objectUrl) { URL.revokeObjectURL(objectUrl); objectUrl = undefined; }
        };
        const read = async () => {
          try {
            const { version, data } = await readWavPreview({
              resourceAddress,
              signal: controller.signal,
              readBytes: (sessionId, filePath, options, signal) => workspaceFiles.readBytes(sessionId, filePath, options, signal),
              readStat: (sessionId, filePath, signal) => workspaceFiles.stat(sessionId, filePath, signal),
            });
            if (disposed || controller.signal.aborted) return;
            objectUrl = URL.createObjectURL(new Blob([data], { type: 'audio/wav' }));
            content.loaded(version);
            setState({ ...owner, url: objectUrl });
          } catch (failure) {
            release();
            if (disposed || controller.signal.aborted) return;
            setState({ ...owner, error: failure?.message ?? String(failure) });
            content.failed();
          }
        };
        void read();
        return () => {
          disposed = true;
          controller.abort();
          try { setAudioRef(undefined); } finally { release(); }
        };
      }, [resourceAddress, revision, workspaceFiles]);
      // A new resource/revision must never render the prior URL, even before
      // React commits the replacement effect and revokes that generation.
      const current = state?.resourceAddress === resourceAddress && state?.revision === revision && state?.workspaceFiles === workspaceFiles ? state : undefined;
      if (current?.error) return h('div', { role: 'alert', style: { padding: 12 } }, current.error);
      if (!current?.url) return h('div', { style: { padding: 12 } }, 'Loading audio…');
      return h('audio', { ref: setAudioRef, controls: true, preload: 'metadata', src: current.url, style: { width: '100%' } });
    }

    return {
      inject: ['documentPreviews', 'slots', 'remote.workspaceFiles'],
      apply(ctx) {
        ctx.effect(() => ctx.documentPreviews.register({
          id: 'oh-my-harness/audio',
          extensions: ['wav'],
          binaryExtensions: ['wav'],
          title: () => 'Audio',
          loading: 'renderer',
          wrap: false,
        }));
        ctx.effect(() => ctx.slots.inject('sidebar.right.tab.document', () => ctx.slots.register({
          name: 'sidebar.right.tab.document',
          key: 'oh-my-harness/audio',
          inject: () => ({ workspaceFiles: ctx.remote.workspaceFiles }),
        }, AudioBody)));
      },
    };
  },
});
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(path.join(here, 'client.js'), build());
  console.log('generated extensions/dsh-capabilities/client.js');
}
