import { expectedHash, expectedVersion, sha256 } from './baseline.mjs';

/** Pure, reviewed source transformation. Never edits the installed host adapter. */
export function patchAdapter(source) {
  if (sha256(source) !== expectedHash) throw new Error('Installed DSH pi adapter fingerprint changed; review the extension before rebuilding');
  let generated = source;
  const replaceOnce = (before, after) => {
    if (generated.split(before).length !== 2) throw new Error('Native adapter patch anchor is not unique');
    generated = generated.replace(before, after);
  };
  replaceOnce(
    '\t\t\tconst model = this.modelOf(snapshot, options.provider, options.model);\n\t\t\tconst updates',
    '\t\t\tconst model = this.modelOf(snapshot, options.provider, options.model);\n\t\t\tconst extension = this.config.prepareStream?.(options, { profile, model });\n\t\t\tconst updates',
  );
  replaceOnce(
    '\t\t\t\tconst iterator = toStreamChunks(snapshot.models.streamSimple(model, context, {',
    '\t\t\t\tconst source = toStreamChunks(snapshot.models.streamSimple(model, context, {',
  );
  replaceOnce(
    '\t\t\t\t\theaders: requestHeaders(profile.headers, options, model.baseUrl, this.config.prepareHeaders)\n\t\t\t\t}), model.contextWindow, options.signal, model.id, digest)[Symbol.asyncIterator]();',
    '\t\t\t\t\theaders: requestHeaders(profile.headers, options, model.baseUrl, this.config.prepareHeaders),\n\t\t\t\t\tfetch: extension?.fetch,\n\t\t\t\t\tonPayload: extension?.onPayload,\n\t\t\t\t\tonProviderStreamEvent: extension?.onProviderStreamEvent\n\t\t\t\t}), model.contextWindow, options.signal, model.id, digest);\n\t\t\t\tconst iterator = (extension?.wrapStream?.(source) ?? source)[Symbol.asyncIterator]();',
  );
  replaceOnce(
    'export { Config, PiAiAdapter, apply, inject, name, recordKeyFor, supportedProtocols };',
    'export { Config, PiAiAdapter, apply, inject, name, recordKeyFor, supportedProtocols, resolveProfiles, credentialStoreFrom, authContextFrom };',
  );
  return `// GENERATED by ../build-adapter.mjs. Upstream MIT, DSH ${expectedVersion}.\n// Upstream SHA-256: ${expectedHash}\n${generated}`;
}
