import { createHash } from 'node:crypto';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { upstreamAdapter } from './paths.mjs';

// Reproducible, version-locked extension: never edit the installed adapter.
export const upstreamPath = path.join(upstreamAdapter, 'lib/index.js');
export const expectedHash = '99b5c20830a52f69641df8a18a39206079b0c725201958cce2c4a934f1d4f7cd';
const sha256 = (text) => createHash('sha256').update(text).digest('hex');
const root = new URL('./', import.meta.url);
const source = await readFile(upstreamPath, 'utf8');
if (sha256(source) !== expectedHash) {
  throw new Error('Installed DSH pi adapter changed. Review the extension against the new version before rebuilding.');
}
let generated = source;
function replaceOnce(before, after) {
  if (generated.split(before).length !== 2) throw new Error(`Adapter patch anchor is not unique: ${before.slice(0, 80)}`);
  generated = generated.replace(before, after);
}
replaceOnce(
  '\t\t\tconst model = this.modelOf(snapshot, options.provider, options.model);\n\t\t\tconst updates',
  '\t\t\tconst model = this.modelOf(snapshot, options.provider, options.model);\n\t\t\tconst extension = this.config.prepareStream?.(options, { profile, model });\n\t\t\tconst updates',
);
replaceOnce(
  '\t\t\t\tconst iterator = toStreamChunks(snapshot.models.streamSimple(model, context, {',
  '\t\t\t\tconst source = toStreamChunks(snapshot.models.streamSimple(model, context, {',
);
replaceOnce(
  '\t\t\t\t\theaders: requestHeaders(profile.headers)\n\t\t\t\t}), model.contextWindow, options.signal, model.id)[Symbol.asyncIterator]();',
  '\t\t\t\t\theaders: requestHeaders(profile.headers),\n\t\t\t\t\tonPayload: extension?.onPayload,\n\t\t\t\t\tonProviderStreamEvent: extension?.onProviderStreamEvent\n\t\t\t\t}), model.contextWindow, options.signal, model.id);\n\t\t\t\tconst iterator = (extension?.wrapStream?.(source) ?? source)[Symbol.asyncIterator]();',
);
replaceOnce(
  'export { Config, PiAiAdapter, apply, inject, name, recordKeyFor, supportedProtocols };',
  'export { Config, PiAiAdapter, apply, inject, name, recordKeyFor, supportedProtocols, resolveProfiles, credentialStoreFrom, authContextFrom };',
);
generated = `// GENERATED by ../build-adapter.mjs. Upstream MIT, DSH 0.2.1-rc.5.\n// Upstream SHA-256: ${expectedHash}\n${generated}`;
const out = new URL('vendor/dsh-pi-adapter.mjs', root);
await mkdir(new URL('vendor/', root), { recursive: true });
// Observe an existing generated file before replacing it.
try { await readFile(out, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
await writeFile(out, generated);
const license = await readFile(path.join(upstreamAdapter, 'LICENSE'), 'utf8');
const licensePath = new URL('vendor/LICENSE', root);
try { await readFile(licensePath, 'utf8'); } catch (error) { if (error.code !== 'ENOENT') throw error; }
await writeFile(licensePath, license);
console.log(JSON.stringify({ output: fileURLToPath(out), upstreamHash: expectedHash, generatedHash: sha256(generated) }));
