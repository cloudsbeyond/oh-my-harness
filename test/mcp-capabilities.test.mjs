import assert from 'node:assert/strict';
import { test } from 'node:test';
import { CapabilityRuntime } from '../src/capabilities/runtime.mjs';
import { createTools, registerCapabilityTools } from '../src/tools.mjs';
import { createRegistry, defaultConfigPath, readConfig } from '../src/config.mjs';
import { registerRealtimeTools } from '../src/realtime.mjs';

test('legacy createTools plus registerRealtimeTools composition registers audio only once', async (t) => {
  const registry = createRegistry(readConfig(defaultConfigPath));
  const server = createTools({ registry, gateway: async () => { throw new Error('No upstream call expected'); } });
  t.after(() => server.close());
  assert.doesNotThrow(() => registerRealtimeTools(server, {
    registry, upstream: new URL('http://127.0.0.1:8317/v1/'), token: 'test-upstream-key-fixture', requestSignal: new AbortController().signal,
  }));
});

const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aJ1sAAAAASUVORK5CYII=', 'base64');
const unpack = (result) => JSON.parse(result.content[0].text);
function fixture() {
  const tools = new Map();
  const calls = [];
  const runtime = new CapabilityRuntime();
  runtime.register({ id: 'independent', models: ['test-model'], operations: ['image.inspect', 'image.generate', 'web.search'], execute: async (operation, input, context) => {
    calls.push({ operation, input, context });
    if (operation === 'image.generate') return { kind: 'image', data: png, mimeType: 'image/png' };
    if (operation === 'web.search') return { kind: 'text', text: 'Found evidence', sources: [{ url: 'https://www.example.com/' }] };
    return { kind: 'text', text: 'A fixture image' };
  } });
  registerCapabilityTools({ registerTool: (name, spec, run) => tools.set(name, { spec, run }) }, { capabilities: runtime });
  const call = (name, args) => { const { spec, run } = tools.get(name); return run(spec.inputSchema.parse(args), { signal: new AbortController().signal }); };
  return { tools, calls, call };
}

test('MCP maps canonical wire image input to bytes for an independent provider', async () => {
  const { call, calls } = fixture();
  assert.deepEqual(unpack(await call('inspect_image', { provider: 'independent', model: 'test-model', question: 'Read it', image_base64: png.toString('base64') })), { answer: 'A fixture image' });
  assert.equal(calls[0].operation, 'image.inspect');
  assert.deepEqual(calls[0].input.images[0].data, png);
  assert.equal(calls[0].input.images[0].mimeType, 'image/png');
  assert.equal(calls[0].input.image_base64, undefined);
  assert.equal(calls[0].context.model, 'test-model');
});

test('MCP maps normalized generated bytes back to the original media envelope', async () => {
  const { call } = fixture();
  const result = await call('generate_image', { prompt: 'A fixture' });
  assert.deepEqual(unpack(result), { mimeType: 'image/png', bytes: png.length });
  assert.deepEqual(result.content[1], { type: 'image', mimeType: 'image/png', data: png.toString('base64') });
});

test('tool registration derives from declared operations rather than fixed provider brands', async () => {
  const { tools, call } = fixture();
  assert.deepEqual([...tools.keys()].sort(), ['generate_image', 'inspect_image', 'list_providers', 'web_search']);
  const listed = unpack(await call('list_providers', {}));
  assert.equal(listed.providers[0].id, 'independent');
  assert.deepEqual(listed.providers[0].capabilities.sort(), ['images', 'search', 'vision']);
  assert.deepEqual(unpack(await call('web_search', { query: 'Topic' })), { answer: 'Found evidence', sources: [{ url: 'https://www.example.com/' }] });
});

test('MCP rejects malformed wire media before provider dispatch', async () => {
  const { call, calls } = fixture();
  await assert.rejects(call('inspect_image', { question: 'Read it', image_base64: 'invalid-base64' }));
  assert.equal(calls.length, 0);
});
